"""Storm DRN/scheduler codecs and public model-type re-exports."""

from __future__ import annotations

from fractions import Fraction
import json
from pathlib import Path
import shlex

from .model import Action, DrnError, DrnModel, State


def _number(text: str) -> float:
    try:
        if "/" in text:
            return float(Fraction(text))
        return float(text)
    except (ValueError, ZeroDivisionError) as error:
        raise DrnError(f"cannot parse DRN number {text!r}") from error


def read_drn(path: Path) -> DrnModel:
    raw_lines = path.read_text(encoding="utf-8").splitlines()
    model_type: str | None = None
    expected_states: int | None = None
    in_model = False
    states: list[State] = []
    current_state: State | None = None
    current_action: Action | None = None
    line_index = 0
    while line_index < len(raw_lines):
        raw = raw_lines[line_index]
        line_index += 1
        stripped = raw.strip()
        if not stripped or stripped.startswith("//"):
            continue
        if not in_model:
            if stripped.startswith("@type:"):
                model_type = stripped.split(":", 1)[1].strip()
            elif stripped == "@nr_states":
                while line_index < len(raw_lines):
                    value = raw_lines[line_index].strip()
                    line_index += 1
                    if value and not value.startswith("//"):
                        expected_states = int(value)
                        break
            elif stripped == "@model":
                in_model = True
            continue
        if stripped.startswith("state "):
            tokens = shlex.split(stripped)
            if len(tokens) < 2:
                raise DrnError(f"malformed state line: {stripped}")
            identifier = int(tokens[1])
            labels = {
                token
                for token in tokens[2:]
                if not token.startswith(("[", "{", "!"))
            }
            current_state = State(identifier, labels, [])
            states.append(current_state)
            current_action = None
        elif stripped.startswith("action "):
            if current_state is None:
                raise DrnError("action occurs before the first state")
            tokens = shlex.split(stripped)
            if len(tokens) < 2:
                raise DrnError(f"malformed action line: {stripped}")
            current_action = Action(tokens[1], [])
            current_state.actions.append(current_action)
        else:
            if current_action is None or ":" not in stripped:
                raise DrnError(f"unexpected DRN line: {stripped}")
            destination, probability = stripped.split(":", 1)
            # Exported probability lines do not carry transition rewards.
            probability_token = probability.strip().split()[0]
            current_action.transitions.append((int(destination.strip()), _number(probability_token)))
    if model_type is None:
        raise DrnError("DRN file has no @type section")
    if expected_states is not None and expected_states != len(states):
        raise DrnError(
            f"DRN declares {expected_states} states but contains {len(states)}"
        )
    model = DrnModel(model_type, states)
    model.validate()
    return model


def write_drn(model: DrnModel, path: Path) -> None:
    model.validate()
    lines = [
        "// Generated by finite-mdp-safety",
        f"@type: {model.model_type}",
        "@value_type: double",
        "@parameters",
        "",
        "@reward_models",
        "",
        "@nr_states",
        str(len(model.states)),
        "@nr_choices",
        str(model.number_of_choices),
        "@model",
    ]
    for state in model.states:
        label_text = " ".join(json.dumps(label) for label in sorted(state.labels))
        suffix = f" {label_text}" if label_text else ""
        lines.append(f"state {state.identifier}{suffix}")
        for action in state.actions:
            lines.append(f"\taction {action.identifier}")
            for successor, probability in action.transitions:
                lines.append(f"\t\t{successor} : {format(probability, '.17g')}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_scheduler(path: Path, model: DrnModel) -> dict[int, int]:
    data = json.loads(path.read_text(encoding="utf-8"))
    global_choices = model.global_choice_map()
    scheduled: dict[int, int] = {}
    for entry in data:
        state_id = int(entry["s"])
        choices = entry.get("c", [])
        positive = [choice for choice in choices if float(choice.get("prob", 0.0)) > 1e-12]
        if len(positive) != 1 or abs(float(positive[0]["prob"]) - 1.0) > 1e-9:
            raise DrnError("single-objective Storm scheduler is unexpectedly randomized")
        global_index = int(positive[0]["index"])
        try:
            owner, local_index = global_choices[global_index]
        except KeyError as error:
            raise DrnError(f"scheduler references unknown choice {global_index}") from error
        if owner != state_id:
            raise DrnError(
                f"scheduler choice {global_index} belongs to state {owner}, not {state_id}"
            )
        scheduled[state_id] = local_index
    return scheduled
